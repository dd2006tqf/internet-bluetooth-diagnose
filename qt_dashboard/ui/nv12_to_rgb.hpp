/**
 * @file nv12_to_rgb.hpp
 * @brief NV12 → RGB888 转换（无 Qt、无摄像头依赖，纯内存变换）
 *
 * ============================================================================
 * 为什么手写而不是用 Qt 的现成能力
 * ============================================================================
 *
 * 本板 sysroot 内**没有 QtMultimedia**（只有 QtCore/QtGui/QtWidgets/QtDBus
 * 等）。`QVideoWidget` / `QVideoFrame` 全部不可用，所以画面只能自己转。
 *
 * `QImage::Format_NV12` 在 Qt 5.15 里**不存在**（它是 Qt 6 才有的格式），
 * 所以 `QImage` 也帮不上忙——它连构造都构造不出来。
 *
 * ============================================================================
 * 为什么单独成一个不依赖 Qt 的模块
 * ============================================================================
 *
 * 转换公式写错的表现是「画面颜色不对」，但那在真机上有无数种原因（传感器、
 * ISP、显示器）。把它做成纯函数之后，可以在 CI 上用**已知输入的纯色块**
 * 断言输出，从而把「公式错」与「链路错」彻底分开。
 *
 * 同理，stride 处理写错的表现是「画面斜切」，UV 偏移处理写错的表现是
 * 「画面偏色」。板端实测（2026-11-14，sunxi-vin，1640×1232 NV12）：
 *
 *   - `bytesperline` 报 **2460**，但 `2460*1232*1.5 = 4546080 > sizeimage
 *     = 3045504`，装不下自己 buffer，**是假值**；真实 stride = 1640（= width）
 *   - UV 平面起始 = **2030336**，而 `stride*height = 2020480`，中间隔着
 *     9856 字节的对齐空洞（实测全零）
 *
 * 所以本模块的 stride **与** uv_offset 都必须是显式传入的**事实值**，
 * 绝不能由 width 或 stride 推导。
 *
 * ============================================================================
 * NV12 的内存布局（务必对照理解，写错这里画面会整体偏色）
 * ============================================================================
 *
 *   Y 平面：height 行 × stride 字节（每像素 1 字节，亮度）
 *   UV 平面：从 `uv_offset` 开始，height/2 行 × stride 字节，**UV 交错**
 *
 * 关键点：
 *   1. UV 平面的**行跨度也是 stride**，不是 width（半宽也不对）；
 *   2. 每个 UV 像素对覆盖 2×2 个 Y 像素，所以 UV 索引要按 (y/2, x/2) 取；
 *   3. UV 平面的起始偏移**一般不是** `stride * height`——标准紧凑 NV12 是，
 *      但 sunxi-vin 会在两个平面之间插入对齐空洞。必须由调用方传入
 *      `uv_offset`（0 表示按 `stride * height` 处理）。
 *
 * 第 3 点是最容易错的一处：用 `stride * height` 硬算在紧凑布局下恰好正确，
 * 在带空洞的布局下会把整块空洞当色度读——空洞是全零，即 U=V=0，
 * 转换出来是饱和度极高的偏色（不是黑屏，所以更容易被误判成"传感器坏了"）。
 */

#pragma once

#include <cstddef>
#include <cstdint>

namespace weaknet {
namespace dashboard {

/**
 * @brief 把一帧 NV12 转成紧凑的 RGB888（每像素 3 字节，无行填充）
 *
 * @param nv12       NV12 源数据起始地址（Y 平面）
 * @param src_size   源数据实际长度。**用于边界校验**：若小于理论所需，
 *                   返回 false 而不是越界读。中枢在源比槽短时会截断
 *                   （`truncated` 计数），此时宁可少画一帧也不能读飞。
 * @param width      图像宽度（像素）
 * @param height     图像高度（像素）。**必须是偶数**：NV12 的 UV 平面按
 *                   2×2 取样，奇数高度会让最后一行没有对应的 UV。
 * @param stride     Y 平面每行字节数。板端实测 1640（`bytesperline` 报的
 *                   2460 是假值）。必须由调用方原样传入，不可推导。
 * @param uv_offset  UV 平面相对 `nv12` 起始的字节偏移。传 0 表示
 *                   「等于 `stride * height`」（标准紧凑 NV12）。
 *                   本板 sunxi-vin 实测真实值是 2030336，而
 *                   `stride*height = 2020480`，两者之间是对齐空洞。
 * @param out        RGB888 输出缓冲，长度必须 >= width*height*3
 * @param out_size   输出缓冲容量
 *
 * @return true 转换成功；false 参数非法或源数据不足（**不抛异常**）
 */
bool nv12ToRgb888(const void* nv12, size_t src_size,
                  uint32_t width, uint32_t height, uint32_t stride,
                  uint32_t uv_offset,
                  uint8_t* out, size_t out_size);

/// 把 RGB888 缩放到目标尺寸（最近邻，供面板降分辨率显示用）
///
/// 为什么需要它：板端是 8 核 A55，1640x1232 约 200 万像素，逐像素 YUV→RGB
/// 每帧要做 200 万次定点运算。这个成本不是「能不能承受」，而是**没有必要**：
/// 面板上的画面框只有几百像素宽，把 1640 宽整幅转完再缩，等于多算了 90% 的
/// 像素。更麻烦的是这段计算**挤在 UI 线程之前的那条取数路径上**，它的抖动
/// 会直接传导到刷新节奏。
///
/// 代价：本模块现阶段的用法是「转全尺寸 → 缩放」（先转换后缩放），因为
/// NV12 直接按源坐标抽样缩放需要另一套布局推导，收益不及风险。若后续
/// 真成为瓶颈，正确的优化方向是**先降采样 Y/UV 再转 RGB**，而不是把
/// 缩放换得更快。
///
/// 最近邻而不是双线性：面板上的画面框通常只有几百像素宽，缩小时双线性的
/// 额外成本换不来可感知的画质差异；而最近邻的取样位置是**确定的**，
/// 便于用已知图案做单测。
///
/// @param src       RGB888 源，尺寸 src_w × src_h
/// @param dst       RGB888 目标，尺寸 dst_w × dst_h
bool scaleRgb888(const uint8_t* src, uint32_t src_w, uint32_t src_h,
                 uint8_t* dst, uint32_t dst_w, uint32_t dst_h);

}  // namespace dashboard
}  // namespace weaknet
