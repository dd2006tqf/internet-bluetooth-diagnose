/**
 * @file video_clip_muxer.hpp
 * @brief 把裸 Annex-B H.264 码流封装成 MP4 容器（调外部 ffmpeg，不重编码）
 *
 * ============================================================================
 * 为什么必须封装，而不是直接把裸码流当留证交付
 * ============================================================================
 *
 * 裸 Annex-B 码流**没有任何时间轴**：它是一串以 `00 00 01` 分隔的 NAL 单元，
 * 既没有帧率也没有时长。后果不是「画质差一点」，而是三件事同时成立：
 *
 *   1. 浏览器 `<video>` 不收 `.h264` 文件，远程查看直接失效；
 *   2. 播放器只能从头线性播，**不能拖进度条**——而事故回看恰恰是
 *      「跳到出事那一刻」，这是留证功能的核心用法；
 *   3. 云端拿不到时长，列表里只能显示字节数，运营无法判断「这段有多长」。
 *
 * ============================================================================
 * 为什么调外部进程，而不是链接 libavformat
 * ============================================================================
 *
 * 链接 libav* 的代价：Bullseye sysroot 里要补齐整套 libav* 的**精确版本**
 * 开发包、glibc 2.31 硬约束、构建体系分叉。这三项在
 * `docs/ideas/视频流产品化-远程查看与事件留证.md` 里被评估过，结论是
 * 「在 mp4mux 能用的情况下没有收益」。
 *
 * 但那是**链接**的代价，不是**调用命令行**的代价——两者完全不同：
 * 板端因 `gstreamer1.0-libav` 早已装齐全部 `libav*` 运行时库，装 `ffmpeg`
 * 实际只多两个包；构建体系一行不用改（不新增任何链接依赖）。
 *
 * 而 GStreamer 的 `mp4mux` 在本仓库这条链路上**做不到**：它硬性要求
 * 输入 buffer 带 PTS（`Buffer has no PTS`），而我们喂进去的是硬件编码器
 * 吐出的裸 Annex-B，没有 PTS/DTS。`avmux_mp4` 能收，但会把 616 帧全部
 * 压到同一个时间戳（`duration=0.006s`），产出**文件能打开、内容全错**的
 * 结果——这比失败更糟。
 *
 * ============================================================================
 * 为什么这件事放在上传线程，而不是编码线程
 * ============================================================================
 *
 * 一次封装实测约 0.26 s（90 KB / 570 帧）。放在编码线程里，这 0.26 s 内
 * 中枢租约会堆积、采集帧被丢弃，而编码线程的纪律是「绝不被下游拖住」
 * （见 `video_clip_exporter.hpp` 里同一理由）。上传线程本来就在等网络，
 * 0.26 s 的本地 CPU 对它没有影响。
 *
 * ============================================================================
 * 已知边界
 * ============================================================================
 *
 * 1. **依赖板端存在 ffmpeg**。这是**运行时**依赖，不是构建依赖——二进制里
 *    不链接任何 libav*。缺失时本模块返回失败，调用方按「保留裸码流」降级
 *    （证据不能因为封装失败而丢失，见 `VideoClipExporter::runOnce`）。
 * 2. **恒定帧率近似**。真实采集是变速的（实测 18.5 fps 上下浮动），而
 *    `-framerate` 只能给一个恒定值。用整段的真实平均帧率，误差在毫秒级，
 *    对「事发那一刻在第几秒」这个用途完全够用；要精确到每帧就需要写
 *    PTS，那得自己实现 muxer。
 * 3. **失败可见**。`VideoClipMuxResult::error` 里带 ffmpeg 的 stderr 摘要，
 *    不含糊成「封装失败」四个字——排障时需要知道是「找不到 ffmpeg」还是
 *    「码流不合规」。
 */

#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace weaknet {

/// ffmpeg 可执行文件的默认路径（Debian 板端）。
///
/// 之所以做成参数而不是写死：在宿主机上它可能装在别处，而单元测试要指向
/// 一个可控的替身。写死会让「这条路径在生产环境成立」变成一个无法验证的
/// 假设——而它恰好是最容易在换板子/换发行版时失效的东西。
constexpr const char* kDefaultFfmpegPath = "/usr/bin/ffmpeg";

/// 封装结果。
struct VideoClipMuxResult {
    bool ok{false};
    /// `ok == true` 时是 MP4 字节；否则为空。
    std::vector<uint8_t> bytes;
    /// `ok == false` 时是给人看的原因（含 ffmpeg stderr 摘要）。
    std::string error;
};

/**
 * @brief 把一段 Annex-B 码流封装为 MP4（H.264 原样拷贝，不重编码）。
 *
 * 为什么不重编码：留证的价值在于「当时就是这个画面」。转码会引入世代损失，
 * 还让板端 CPU 从 0.26 s 变成几十秒量级——事故期间本来就在丢帧，再加一个
 * 重编码只会让现场更糟。`-c copy` 只搬字节、只写容器。
 *
 * @param data        拼接后的 Annex-B 码流（必须以 SPS/PPS 起头才能被解出）
 * @param size        字节数
 * @param frame_count 片段内的帧数。>1 时与 `span_ms` 一起推导精确帧率；
 *                    无法推导时退化为默认 25 fps 并在 error 里说明**仅当失败时**。
 * @param span_ms     首帧到末帧的单调时间跨度（毫秒）
 * @param ffmpeg_path ffmpeg 可执行文件路径
 * @return 成功时 `bytes` 是完整 MP4；失败时 `error` 说明原因，`bytes` 为空
 */
VideoClipMuxResult muxAnnexBToMp4(const uint8_t* data, size_t size,
                                  uint32_t frame_count, uint32_t span_ms,
                                  const std::string& ffmpeg_path = kDefaultFfmpegPath);

/**
 * @brief 嗅探 MP4 容器（前 12 字节里第 4..8 字节是否为 `ftyp` box 类型）。
 *
 * 为什么靠嗅探而不是靠清单字段：容器类型是**码流自身的事实**，已经在字节里。
 * 再在清单里声明一份就等于允许两者不一致，而不一致时以谁为准没有答案。
 * 云端的下载端点用同一个判据决定 `Content-Type`——它没有别的可信来源
 * （历史片段是裸码流，新片段是 MP4，两者会长期共存）。
 *
 * 判据本身足够严格：Annex-B 以 `00 00 00 01` / `00 00 01` 起头，
 * 与该位置上的 `ftyp` 不可能混淆。
 */
bool looksLikeMp4(const uint8_t* data, size_t size);

}  // namespace weaknet
