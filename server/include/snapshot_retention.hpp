/**
 * @file snapshot_retention.hpp
 * @brief 板端静帧目录的容量回收：按总字节上限，从最旧的事故目录开始删
 *
 * ============================================================================
 * 为什么板端也需要回收，而云端已经有保留策略了
 * ============================================================================
 *
 * 两端的角色完全不同：
 *
 * ```
 *   板端 SnapshotService ──落盘──> data/snapshots/<incident>/<ms>_<seq>.jpg
 *                       ──上传──> 云端 network_snapshot_images（证据的权威副本）
 * ```
 *
 * 云端的保留策略管的是**权威副本**：过期就删，因为板子那边的事故早就结束了。
 * 板端这份是**发送缓冲 + 离线副本**，两者不能共用一套判据：
 *
 *   - 板子可能长时间离线。这时本地这份是**唯一**的副本，云端一条记录都没有；
 *   - 反过来，上传成功后本地这份的使命就结束了，但它还有「事故现场还能在
 *     本机翻出来」的价值，所以不能一上传就删。
 *
 * 于是板端的判据只有一条：**磁盘占用别无限长**。它不判断证据该不该留，只
 * 判断这块盘还装不装得下。
 *
 * ============================================================================
 * 为什么按「总字节上限」而不是「保留天数」
 * ============================================================================
 *
 * 板子没有 RTC（重启后墙钟可能是 1970 或任何值），而文件名用的是**墙钟**
 * 毫秒。用「文件的 mtime/文件名早于 N 天」来删，一块时钟跳错的板子会一次性
 * 把所有图判成过期。总字节上限与时钟无关：它只问「现在占了多少」。
 *
 * 顺序判据用**文件名里的毫秒数**（同一事故内单调），跨目录用**目录内最旧
 * 文件的名字**排序——仍然依赖墙钟大小关系，但即使时钟整体偏移，**相对顺序
 * 依然正确**（时钟跳变会让顺序错乱，但不会让「谁更旧」这件事变成「谁该被
 * 全删」）。这是本模块能在无 RTC 的板子上成立的关键。
 *
 * ============================================================================
 * 为什么绝不删除「刚写进来的那一张」
 * ============================================================================
 *
 * 上限可能被配得比一张图还小（配置失误）。此时「删到装得下」的唯一解法是
 * 删掉刚拍的图，于是事故发生时拍一张、立刻消失——而上传线程可能还没取到它。
 * 所以回收会显式跳过本次新增的文件，并在装不下时告警，让配置错误可见。
 *
 * ============================================================================
 * 为什么失败只告警
 * ============================================================================
 *
 * 回收跑在快照工作线程里，紧跟一次成功落盘之后。让它抛错或返回失败会影响
 * 「这张图存下来了」这个已经成立的事实。删不掉（权限、忙）只记日志：下一次
 * 落盘还会再试。
 */

#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace weaknet {

/// 回收判据与结果
struct SnapshotRetentionConfig {
    /// 整个 snapshots 目录的总字节上限。0 表示**不回收**（默认关闭）。
    ///
    /// 默认 0 而不是一个数字：没人复核过的数字不该开始删证据。与云端
    /// `SNAPSHOT_RETENTION_DAYS` 没有默认值是同一个理由。
    uint64_t max_total_bytes{0};

    /// 单次回收最多删除多少个文件。防止上限被误配成 1 字节时一次扫掉整个目录。
    size_t max_files_per_run{32};
};

/// 一次回收的结果。全部是**可观测**的事实，不含推测。
struct SnapshotRetentionResult {
    /// 回收前的总字节
    uint64_t bytes_before{0};
    /// 回收后的总字节
    uint64_t bytes_after{0};
    /// 实际删掉的文件数
    size_t files_deleted{0};
    /// 删掉文件的字节数
    uint64_t bytes_freed{0};
    /// 尝试但失败的次数（权限/忙）。这些文件下一轮还会被看到。
    size_t delete_failures{0};
    /// 删除后仍超上限（上限比现有最旧的一张还小，或被 keep 卡住）
    bool still_over_limit{false};
    /// 被删除后变空的目录数（顺带清理，避免目录无限增长）
    size_t dirs_removed{0};
};

/// 目录扫描的一条结果
struct SnapshotFileEntry {
    std::string path;      ///< 完整路径
    std::string incident;  ///< 所属事故目录名
    uint64_t size_bytes{0};
    uint64_t name_ms{0};   ///< 文件名里的墙钟毫秒（解析失败为 0）
};

/**
 * @brief 扫描 snapshots 根目录下的 `<incident>/<ms>_<seq>.jpg`，按「最旧在前」排序
 *
 * 只认两层结构：根目录下的子目录里的 `*.jpg`（以及残留的 `*.jpg.tmp`——
 * 它们是原子写崩溃后留下的半成品，比正式文件更该被清掉）。
 *
 * 不递归更深层：落盘布局由 `SnapshotService` 固定为两层，多扫一层只会让
 * 「这条路是谁写的」变得无法回答。
 *
 * 排序规则：`name_ms` 升序；相同则按路径字典序。**显式排序而不是依赖
 * readdir 顺序**——后者由文件系统决定，同一输入在不同板子上会得到不同结果，
 * 而回收顺序直接决定「哪张证据先被删」。
 *
 * @param root snapshots 根目录
 * @param out  结果（会被清空后填充）
 * @return false 表示根目录打不开（不存在视为空，返回 true）
 */
bool scanSnapshotFiles(const std::string& root, std::vector<SnapshotFileEntry>* out);

/**
 * @brief 回收：删最旧的，直到总量回到上限以内
 *
 * @param root   snapshots 根目录
 * @param config 判据
 * @param keep_path 本次刚写的文件路径；为空表示没有要保护的。
 *                  **它一定不会被删**，即使它是唯一的文件且超上限。
 * @param result 结果（可为空）
 * @return 被删掉的文件数
 */
size_t pruneSnapshotDir(const std::string& root,
                        const SnapshotRetentionConfig& config,
                        const std::string& keep_path,
                        SnapshotRetentionResult* result);

}  // namespace weaknet
